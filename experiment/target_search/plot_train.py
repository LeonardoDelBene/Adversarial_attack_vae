def main():
    parser = argparse.ArgumentParser(description="Plot storia ottimizzazione mu_target")
    parser.add_argument(
        "--out",
        type=str,
        default="target_search_plot.png",
        help="Path di output per il grafico",
    )
    parser.add_argument("--dpi", type=int, default=200)
    args = parser.parse_args()

    epochs = [d[0] for d in DATA]
    l_vae = [d[1] for d in DATA]
    l_noise = [d[2] for d in DATA]

    fig, ax1 = plt.subplots(figsize=(8, 5))

    color_vae = "tab:blue"
    ax1.set_xlabel("Epoca")
    ax1.set_ylabel(r"$L_{vae}$", color=color_vae)
    line1, = ax1.plot(epochs, l_vae, color=color_vae, linewidth=2, label=r"$L_{vae}$")
    ax1.tick_params(axis="y", labelcolor=color_vae)
    ax1.grid(True, alpha=0.3)

    ax2 = ax1.twinx()
    color_noise = "tab:red"
    ax2.set_ylabel(r"$L_{noise}$", color=color_noise)
    line2, = ax2.plot(epochs, l_noise, color=color_noise, linewidth=2, linestyle="--", label=r"$L_{noise}$")
    ax2.tick_params(axis="y", labelcolor=color_noise)
    ax2.set_ylim(0.023, 0.025)

    lines = [line1, line2]
    labels = [l.get_label() for l in lines]
    ax1.legend(lines, labels, loc="upper right")

    plt.title("Convergenza della ricerca del target universale (mu_target)")
    fig.tight_layout()
    plt.savefig(args.out, dpi=args.dpi, bbox_inches="tight")
    print(f"Grafico salvato in: {args.out}")


if __name__ == "__main__":
    main()